#!/usr/bin/env python3
"""Generate Go code from the catalogs extracted from Bambu Handy 4.2.2.

Inputs:  catalog/models.json, catalog/endpoints.json, catalog/mqtt_commands.json
Outputs: pkg/bambu/cloud/model/models_gen.go
         pkg/bambu/cloud/endpoints_gen.go
         pkg/bambu/mqtt/commands_gen.go

Usage: python3 tools/gen_go.py [repo-root]
"""
import json
import os
import re
import sys
from collections import OrderedDict

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

GO_KEYWORDS = {"break", "default", "func", "interface", "select", "case", "defer", "go", "map", "struct",
               "chan", "else", "goto", "package", "switch", "const", "fallthrough", "if", "range", "type",
               "continue", "for", "import", "return", "var"}
# Names that would collide with Go predeclared identifiers or package-level helpers.
RESERVED_TYPE_NAMES = {"Error", "String", "Int", "Bool", "Map", "List", "Any", "Client", "Endpoint", "Region"}

HEADER = "// Code generated by tools/gen_go.py from catalog/*.json; DO NOT EDIT.\n// Source: Bambu Handy 4.2.2 (bbl.intl.bambulab.com, versionCode 40202).\n\n"


def load(name):
    with open(os.path.join(ROOT, "catalog", name)) as f:
        return json.load(f)


def pascal(s: str) -> str:
    s = re.sub(r"[^0-9A-Za-z]+", " ", s)
    parts = [p for p in s.split(" ") if p]
    out = "".join(p[0].upper() + p[1:] for p in parts)
    if out and out[0].isdigit():
        out = "N" + out
    return out


def go_ident(s: str) -> str:
    s = pascal(s)
    if s in GO_KEYWORDS:
        s += "_"
    return s


# ----------------------------------------------------------------------------- Java -> Go types

def parse_java_type(t: str):
    """Parse 'Map<String, List<Foo>>' into ('Map', [('String',[]), ('List',[('Foo',[])])])."""
    t = t.strip()
    t = re.sub(r"^\? (extends|super) ", "", t)
    m = re.match(r"^([\w.$]+)(?:<(.*)>)?$", t)
    if not m:
        return (t, [])
    name, args = m.group(1), m.group(2)
    if not args:
        return (name, [])
    parts, depth, cur = [], 0, ""
    for ch in args:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return (name, [parse_java_type(p) for p in parts])


class TypeMapper:
    def __init__(self, models, model_pkg_prefix=""):
        self.models = models  # fqn -> record
        self.prefix = model_pkg_prefix  # "" inside model package, "model." elsewhere
        self.go_names = unique_go_names(models)  # fqn -> Go type name
        self.by_simple = {}
        for fqn in models:
            self.by_simple.setdefault(fqn.rsplit(".", 1)[-1], []).append(fqn)

    def go(self, java: str, type_params=(), boxed_ptr=True, refs=None):
        """Map a Java type string to a Go type. refs: simple name -> fqn for the referencing file."""
        name, args = parse_java_type(java)
        return self._go(name, args, type_params, boxed_ptr, refs or {})

    def lookup(self, simple, refs):
        fqn = refs.get(simple)
        if fqn is None:
            cands = self.by_simple.get(simple, [])
            fqn = cands[0] if cands else None
        rec = self.models.get(fqn) if fqn else None
        return fqn, rec

    def _go(self, name, args, type_params, boxed_ptr, refs):
        prim = {"int": "int", "Integer": "int", "long": "int64", "Long": "int64", "boolean": "bool",
                "Boolean": "bool", "double": "float64", "Double": "float64", "float": "float32",
                "Float": "float32", "short": "int16", "Short": "int16", "byte": "int8", "Byte": "int8",
                "char": "rune", "Character": "rune", "String": "string", "CharSequence": "string",
                "BigDecimal": "json.Number", "Number": "json.Number"}
        boxed = {"Integer", "Long", "Boolean", "Double", "Float", "Short", "Byte", "Character"}
        if name in prim:
            g = prim[name]
            if boxed_ptr and name in boxed:
                return "*" + g
            return g
        if name in ("Object", "Any", "T", "R", "E", "V", "K") and name in type_params:
            return name
        if name in ("Object", "Any", "JsonElement", "JsonPrimitive"):
            return "any"
        if name in ("JsonObject",):
            return "map[string]any"
        if name == "JsonArray":
            return "[]any"
        if name in ("List", "Set", "Collection", "ArrayList", "Iterable", "MutableList"):
            inner = self._go(*args[0], type_params, False, refs) if args else "any"
            return "[]" + inner
        if name in ("Map", "HashMap", "LinkedHashMap", "MutableMap"):
            k = self._go(*args[0], type_params, False, refs) if args else "string"
            v = self._go(*args[1], type_params, False, refs) if len(args) > 1 else "any"
            return "map[" + k + "]" + v
        if name in ("pqs", "Unit", "Void", "void"):
            return ""
        if name == "dfo":  # okhttp3.ResponseBody
            return "[]byte"
        if name == "p45":  # kotlin.Result-like wrapper -> unwrap
            return self._go(*args[0], type_params, boxed_ptr, refs) if args else "any"
        simple = name.rsplit(".", 1)[-1].replace("$", "")
        if simple in type_params:
            return simple
        fqn, rec = self.lookup(simple, refs)
        if rec is None:
            return "json.RawMessage"
        gname = self.prefix + self.go_names[fqn]
        if rec.get("typeParams"):
            targs = [self._go(*a, type_params, False, refs) for a in args] or ["any"] * len(rec["typeParams"])
            gname += "[" + ", ".join(targs) + "]"
        return gname

    def is_class(self, simple, refs):
        _, rec = self.lookup(simple, refs)
        return rec is not None and rec["kind"] == "class"


def unique_go_names(models):
    """fqn -> Go type name; same-named classes from different packages get package-derived prefixes."""
    groups = {}
    for fqn in models:
        groups.setdefault(fqn.rsplit(".", 1)[-1], []).append(fqn)
    names = {}
    for simple, fqns in groups.items():
        base = go_ident(simple)
        if base in RESERVED_TYPE_NAMES:
            base += "Model"
        if len(fqns) == 1:
            names[fqns[0]] = base
            continue
        k = 1
        while True:
            cand = {}
            for fqn in fqns:
                segs = fqn.split(".")[:-1]
                cand[fqn] = "".join(pascal(x) for x in segs[-k:]) + base
            if len(set(cand.values())) == len(fqns) or k > 8:
                names.update(cand)
                break
            k += 1
    return names


# ----------------------------------------------------------------------------- models

def gen_models(models):
    tm = TypeMapper(models)
    out = [HEADER, "package model\n\n", "import \"encoding/json\"\n\n", "var _ = json.RawMessage(nil)\n\n"]
    for fqn in sorted(models, key=lambda f: tm.go_names[f]):
        rec = models[fqn]
        gname = tm.go_names[fqn]
        fq = fqn
        refs = rec.get("refs", {})
        if rec["kind"] == "enum":
            out.append(f"// {gname} is {fq}.\ntype {gname} string\n\nconst (\n")
            seen = set()
            for v in rec.get("values", []):
                cname = gname + go_ident(v["name"])
                if cname in seen:
                    continue
                seen.add(cname)
                out.append(f"\t{cname} {gname} = {json.dumps(v['json'])}\n")
            out.append(")\n\n")
            continue
        tparams = rec.get("typeParams") or []
        tp = "[" + ", ".join(f"{t} any" for t in tparams) + "]" if tparams else ""
        out.append(f"// {gname} is {fq}.\ntype {gname}{tp} struct {{\n")
        used = set()
        for f in rec.get("fields", []):
            fname = go_ident(f["prop"])
            base = fname
            i = 2
            while fname in used:
                fname = f"{base}{i}"
                i += 1
            used.add(fname)
            optional = f.get("optional", True)
            gt = tm.go(f["javaType"], tparams, boxed_ptr=True, refs=refs)
            name, _ = parse_java_type(f["javaType"])
            simple_ref = name.rsplit(".", 1)[-1]
            if simple_ref not in tparams and tm.is_class(simple_ref, refs) and optional and not gt.startswith("*"):
                gt = "*" + gt
            tag = f["json"]
            if optional and not gt.startswith("*") and gt not in ("any",):
                tag += ",omitempty"
            elif optional and gt.startswith("*"):
                tag += ",omitempty"
            out.append(f"\t{fname} {gt} `json:\"{tag}\"`\n")
        out.append("}\n\n")
    return "".join(out)


# ----------------------------------------------------------------------------- endpoints

SERVICE_RE = re.compile(r"^([a-z0-9-]+)/")


def endpoint_name(http, path):
    segs = []
    for seg in path.split("/"):
        if not seg:
            continue
        m = re.fullmatch(r"\{(\w+)\}", seg)
        if m:
            segs.append("By" + pascal(m.group(1)))
        else:
            segs.append(pascal(seg))
    return pascal(http.lower()) + "".join(segs)


# Query/header names the extractor could not resolve because the annotation
# used a constant from another class. Resolved by hand from the decompiled
# sources (io.sentry.protocol.Device.JsonKeys.MODEL_ID, PictureMimeType.MIME_TYPE_PREFIX_IMAGE).
UNNAMED_PARAM_FIXUPS = {
    ("iot-service/api/user/profile/{profile_id}", "path", "str"): "profile_id",
    ("iot-service/api/user/profile/{profile_id}", "query", "str2"): "model_id",
    ("search-service/select/all", "query", "str2"): "image",
    ("search-service/select/design2", "query", "str2"): "image",
}


def merge_endpoints(eps, endpoint_refs):
    groups = OrderedDict()
    for ep in eps:
        refs = endpoint_refs.get(ep["interface"], {})
        if ep["path"] in ("", None) or any(p["kind"] == "url" for p in ep["params"]):
            continue
        key = (ep["http"], ep["path"])
        g = groups.setdefault(key, {"http": ep["http"], "path": ep["path"], "params": OrderedDict(),
                                    "response": None, "interfaces": [], "hasBody": ep["hasBody"], "refs": {}})
        g["interfaces"].append(ep["interface"] + "." + ep["method"])
        for p in ep["params"]:
            if p["kind"] == "tag":
                continue
            if p["name"] is None and p["kind"] in ("query", "header", "path"):
                fixed = UNNAMED_PARAM_FIXUPS.get((ep["path"], p["kind"], p.get("var")))
                if fixed is None:
                    continue
                p = dict(p, name=fixed)
            k = (p["kind"], p["name"])
            if k not in g["params"]:
                g["params"][k] = dict(p, refs=refs)
        if g["response"] in (None, "pqs") and ep["response"] not in ("pqs",):
            g["response"] = ep["response"]
            g["refs"] = refs
        elif g["response"] is None:
            g["response"] = ep["response"]
            g["refs"] = refs
    return list(groups.values())


def param_go_type(tm, p):
    jt = p["javaType"]
    refs = p.get("refs", {})
    if p["kind"] == "path":
        return tm.go(jt, boxed_ptr=False)
    if p["kind"] == "body":
        g = tm.go(jt, boxed_ptr=False, refs=refs)
        if g.startswith("model."):
            return "*" + g
        return g
    if p["kind"] == "querymap":
        return "map[string]string"
    # query / header
    g = tm.go(jt, boxed_ptr=False)
    if jt in ("int", "long", "boolean", "double"):
        return g
    return "*" + g


def fmt_expr(gt, expr):
    """Go expression converting value of type gt (non-pointer) to string."""
    if gt == "string":
        return expr
    if gt == "int":
        return f"strconv.Itoa({expr})"
    if gt == "int64":
        return f"strconv.FormatInt({expr}, 10)"
    if gt == "bool":
        return f"strconv.FormatBool({expr})"
    if gt == "float64":
        return f"strconv.FormatFloat({expr}, 'f', -1, 64)"
    return f"fmt.Sprint({expr})"


def gen_endpoints(eps, models, endpoint_refs):
    tm = TypeMapper(models, "model.")
    merged = merge_endpoints(eps, endpoint_refs)
    names = {}
    for g in merged:
        n = endpoint_name(g["http"], g["path"])
        base, i = n, 2
        while n in names:
            n = f"{base}{i}"
            i += 1
        names[n] = g
        g["name"] = n
    out = [HEADER, "package cloud\n\n",
           "import (\n\t\"context\"\n\t\"fmt\"\n\t\"net/http\"\n\t\"net/url\"\n\t\"strconv\"\n\n\t\"github.com/lordbagel42/bambu-rea/pkg/bambu/cloud/model\"\n)\n\n",
           "var (\n\t_ = fmt.Sprint\n\t_ = strconv.Itoa\n\t_ = url.PathEscape\n\t_ model.DeviceData\n)\n\n"]
    registry = []
    for g in sorted(merged, key=lambda g: g["name"]):
        name = g["name"]
        params = list(g["params"].values())
        path_params = [p for p in params if p["kind"] == "path"]
        opt_params = [p for p in params if p["kind"] in ("query", "querymap", "header") and p["name"] != "Authorization"]
        body = next((p for p in params if p["kind"] == "body"), None)
        resp = tm.go(g["response"] or "pqs", refs=g["refs"])
        svc = SERVICE_RE.match(g["path"])
        service = svc.group(1) if svc else ""
        signed = any(p["name"] == "x-bbl-device-security-sign" for p in opt_params)
        # --- params struct
        pstruct = None
        if opt_params:
            pstruct = name + "Params"
            out.append(f"// {pstruct} holds optional query/header parameters for {name}.\ntype {pstruct} struct {{\n")
            used = set()
            for p in opt_params:
                if p["kind"] == "querymap":
                    fname = "QueryMap"
                else:
                    fname = go_ident(p["name"])
                b, i = fname, 2
                while fname in used:
                    fname = f"{b}{i}"
                    i += 1
                used.add(fname)
                p["goField"] = fname
                gt = param_go_type(tm, p)
                p["goType"] = gt
                tagkind = "query" if p["kind"] in ("query", "querymap") else "header"
                out.append(f"\t{fname} {gt} `{tagkind}:\"{p['name'] or '*'}\"`\n")
            out.append("}\n\n")
        # --- signature
        args = ["ctx context.Context"]
        for p in path_params:
            p["goArg"] = lower_first(go_ident(p["name"]))
            p["goType"] = param_go_type(tm, p)
            args.append(f"{p['goArg']} {p['goType']}")
        if body is not None:
            body["goType"] = param_go_type(tm, body)
            args.append(f"body {body['goType']}")
        if pstruct:
            args.append(f"p *{pstruct}")
        ret = "error" if resp == "" else f"({resp}, error)"
        doc = f"// {name} calls {g['http']} {g['path']} (from {', '.join(g['interfaces'][:3])}).\n"
        if signed:
            doc += "// This endpoint carries the IoT app-certificate signature headers; the client fills them from its Signer when unset.\n"
        out.append(doc)
        out.append(f"func (c *Client) {name}({', '.join(args)}) {ret} {{\n")
        # path
        if path_params:
            parts = []
            for seg in g["path"].split("/"):
                m = re.fullmatch(r"\{(\w+)\}", seg)
                if m:
                    p = next(pp for pp in path_params if pp["name"] == m.group(1))
                    parts.append(f"url.PathEscape({fmt_expr(p['goType'], p['goArg'])})")
                else:
                    parts.append(json.dumps(seg))
            out.append("\tpath := " + " + \"/\" + ".join(parts) + "\n")
        else:
            out.append(f"\tpath := {json.dumps(g['path'])}\n")
        out.append("\tq := url.Values{}\n\th := http.Header{}\n")
        if pstruct:
            out.append("\tif p != nil {\n")
            for p in opt_params:
                gt, f = p["goType"], "p." + p["goField"]
                if p["kind"] == "querymap":
                    out.append(f"\t\tfor k, v := range {f} {{\n\t\t\tq.Set(k, v)\n\t\t}}\n")
                    continue
                setter = "q.Set" if p["kind"] == "query" else "h.Set"
                if gt.startswith("*"):
                    out.append(f"\t\tif {f} != nil {{\n\t\t\t{setter}({json.dumps(p['name'])}, {fmt_expr(gt[1:], '*' + f)})\n\t\t}}\n")
                else:
                    out.append(f"\t\t{setter}({json.dumps(p['name'])}, {fmt_expr(gt, f)})\n")
            out.append("\t}\n")
        bodyexpr = "body" if body is not None else "nil"
        if resp == "":
            out.append(f"\treturn c.call(ctx, &Endpoint{name}, path, q, h, {bodyexpr}, nil)\n}}\n\n")
        else:
            out.append(f"\tvar out {resp}\n\terr := c.call(ctx, &Endpoint{name}, path, q, h, {bodyexpr}, &out)\n\treturn out, err\n}}\n\n")
        # registry
        specs = []
        for p in params:
            if p["name"] == "Authorization":
                continue
            specs.append(f"{{Kind: {json.dumps(p['kind'])}, Name: {json.dumps(p['name'] or '')}, JavaType: {json.dumps(p['javaType'])}}}")
        out.append(f"// Endpoint{name} describes {g['http']} {g['path']}.\nvar Endpoint{name} = Endpoint{{Name: {json.dumps(name)}, Method: {json.dumps(g['http'])}, Path: {json.dumps(g['path'])}, Service: {json.dumps(service)}, Response: {json.dumps(g['response'] or 'pqs')}, Signed: {str(signed).lower()}, Params: []ParamSpec{{{', '.join(specs)}}}}}\n\n")
        registry.append(name)
    out.append("// Endpoints lists every cloud endpoint the Handy app can call.\nvar Endpoints = []*Endpoint{\n")
    for n in registry:
        out.append(f"\t&Endpoint{n},\n")
    out.append("}\n")
    return "".join(out), len(registry)


def lower_first(s):
    s = s[0].lower() + s[1:]
    if s in GO_KEYWORDS:
        s += "_"
    return s


# ----------------------------------------------------------------------------- mqtt commands

MQTT_TYPES = {"string": "string", "int": "int", "long": "int64", "double": "float64", "bool": "bool",
              "string[]": "[]string", "int[]": "[]int", "object": "map[string]any", "object[]": "[]map[string]any", "any": "any"}


def gen_commands(cat):
    out = [HEADER, "package mqtt\n\n"]
    specs = []
    for c in cat["commands"]:
        name = c["name"]
        params = c.get("params", [])
        raw = c.get("rawParams", False)
        gcode = c.get("gcodeBuilder")
        doc = c.get("doc", "")
        enc = c.get("encryptFields", [])
        consts = {p["key"]: p["const"] for p in params if "const" in p}
        consts.update(c.get("constParams", {}))
        # spec
        pspecs = []
        for p in params:
            pspecs.append("{Key: %s, Type: %s, Optional: %s, Const: %s, Derived: %s, Wire: %s}" % (
                json.dumps(p["key"]), json.dumps(p["type"]), str(bool(p.get("optional"))).lower(),
                go_literal(p["const"]) if "const" in p else "nil", json.dumps(p.get("derived", "")), json.dumps(p.get("wire", ""))))
        specs.append("\t{Name: %s, Module: %s, Command: %s, EncryptFields: %s, RawParams: %s, GcodeBuilder: %s, ConstParams: %s, Doc: %s, Params: []ParamSpec{%s}}" % (
            json.dumps(name), json.dumps(c["module"]), json.dumps(c["command"]), go_str_slice(enc), str(raw).lower(),
            json.dumps(gcode or ""), go_any_map(c.get("constParams", {})), json.dumps(doc), ", ".join(pspecs)))
        if gcode:
            continue  # hand-written builder in gcode.go
        user_params = [p for p in params if "const" not in p and not p.get("derived")]
        docline = f"// {name} builds {c['module']}/{c['command']}." + (f" {doc}" if doc else "") + "\n"
        if raw:
            out.append(docline)
            out.append(f"func {name}(params map[string]any) Command {{\n\tp := make(map[string]any, len(params)+{len(consts)})\n\tfor k, v := range params {{\n\t\tp[k] = v\n\t}}\n")
            for k, v in consts.items():
                out.append(f"\tp[{json.dumps(k)}] = {go_literal(v)}\n")
            out.append(f"\treturn Command{{Module: {json.dumps(c['module'])}, Command: {json.dumps(c['command'])}, Params: p, EncryptFields: {go_str_slice(enc)}}}\n}}\n\n")
            continue
        if not user_params:
            out.append(docline)
            out.append(f"func {name}() Command {{\n")
            if consts:
                out.append("\tp := map[string]any{\n")
                for k, v in consts.items():
                    out.append(f"\t\t{json.dumps(k)}: {go_literal(v)},\n")
                out.append("\t}\n")
                out.append(f"\treturn Command{{Module: {json.dumps(c['module'])}, Command: {json.dumps(c['command'])}, Params: p, EncryptFields: {go_str_slice(enc)}}}\n}}\n\n")
            else:
                out.append(f"\treturn Command{{Module: {json.dumps(c['module'])}, Command: {json.dumps(c['command'])}, EncryptFields: {go_str_slice(enc)}}}\n}}\n\n")
            continue
        sname = name + "Params"
        out.append(f"// {sname} are the parameters of {name}.\ntype {sname} struct {{\n")
        for p in user_params:
            gt = MQTT_TYPES[p["type"]]
            if p.get("optional") and not gt.startswith("[]") and gt not in ("any", "map[string]any"):
                gt = "*" + gt
            fdoc = f" // {p['doc']}" if p.get("doc") else ""
            out.append(f"\t{go_ident(p['key'])} {gt} `json:\"{p['key']}{',omitempty' if p.get('optional') else ''}\"`{fdoc}\n")
        out.append("}\n\n")
        out.append(docline)
        out.append(f"func {name}(a {sname}) Command {{\n\tp := map[string]any{{}}\n")
        for p in params:
            key = json.dumps(p["key"])
            if "const" in p:
                out.append(f"\tp[{key}] = {go_literal(p['const'])}\n")
                continue
            src = "a." + go_ident(p.get("derived") or p["key"])
            gt = MQTT_TYPES[p["type"]]
            wire = p.get("wire", "")
            optional = p.get("optional") and not gt.startswith("[]") and gt not in ("any", "map[string]any")
            if p.get("derived"):
                dp = next(pp for pp in params if pp["key"] == p["derived"])
                optional = dp.get("optional") and not MQTT_TYPES[dp["type"]].startswith("[]")
            val = "*" + src if optional else src
            expr = {"enable_disable": f"enableDisable({val})", "upper": f"strings.ToUpper({val})",
                    "int01": f"boolInt({val})", "gcode": f"ensureGcodeTerminator({val})"}.get(wire, val)
            if optional:
                out.append(f"\tif {src} != nil {{\n\t\tp[{key}] = {expr}\n\t}}\n")
            elif gt.startswith("[]") or gt in ("map[string]any",):
                out.append(f"\tif {src} != nil {{\n\t\tp[{key}] = {expr}\n\t}}\n")
            else:
                out.append(f"\tp[{key}] = {expr}\n")
        if c["command"] == "clean_print_error":
            out.append("\tif len(p) == 0 {\n\t\tp = nil\n\t}\n")
        out.append(f"\treturn Command{{Module: {json.dumps(c['module'])}, Command: {json.dumps(c['command'])}, Params: p, EncryptFields: {go_str_slice(enc)}}}\n}}\n\n")
    out.append("// Specs lists every MQTT command the Handy app can send, in catalog order.\nvar Specs = []CommandSpec{\n" + ",\n".join(specs) + ",\n}\n")
    src = "".join(out)
    if "strings.ToUpper" in src:
        src = src.replace("package mqtt\n\n", "package mqtt\n\nimport \"strings\"\n\n", 1)
    return src, len(specs)


def go_literal(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return json.dumps(v)


def go_str_slice(xs):
    if not xs:
        return "nil"
    return "[]string{" + ", ".join(json.dumps(x) for x in xs) + "}"


def go_any_map(d):
    if not d:
        return "nil"
    return "map[string]any{" + ", ".join(f"{json.dumps(k)}: {go_literal(v)}" for k, v in d.items()) + "}"


def write(rel, content):
    p = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(content)
    print("wrote", rel)


